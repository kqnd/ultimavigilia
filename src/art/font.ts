const ACCENTS: Record<string, string[]> = {
  acute: ['.#', '#.'],
  grave: ['#.', '.#'],
  circ: ['.#.', '#.#'],
  tilde: ['.#.#', '#.#.'],
};

const COMPOSED: Record<string, [string, keyof typeof ACCENTS | 'cedilla']> = {
  á: ['a', 'acute'], à: ['a', 'grave'], â: ['a', 'circ'], ã: ['a', 'tilde'],
  é: ['e', 'acute'], ê: ['e', 'circ'], í: ['i', 'acute'], ó: ['o', 'acute'], ô: ['o', 'circ'], õ: ['o', 'tilde'],
  ú: ['u', 'acute'], ü: ['u', 'circ'], ç: ['c', 'cedilla'],
  Á: ['A', 'acute'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'tilde'], É: ['E', 'acute'], Ê: ['E', 'circ'],
  Í: ['I', 'acute'], Ó: ['O', 'acute'], Ô: ['O', 'circ'], Õ: ['O', 'tilde'], Ú: ['U', 'acute'], Ç: ['C', 'cedilla'],
};

export interface Glyph {
  w: number;
  /** FONT_CELL_H linhas de largura w, '#' = pixel. */
  rows: string[];
}

function blank(w: number): string[] {
  return Array.from({ length: FONT_CELL_H }, () => '.'.repeat(w));
}

function place(dst: string[], src: string[], x: number, y: number): void {
  src.forEach((r, i) => {
    const row = dst[y + i];
    if (row === undefined) return;
    let out = row;
    for (let k = 0; k < r.length; k++) if (r[k] === '#') out = out.slice(0, x + k) + '#' + out.slice(x + k + 1);
    dst[y + i] = out;
  });
}

let cache: Map<string, Glyph> | null = null;

export function getFont(): Map<string, Glyph> {
  if (cache) return cache;
  const m = new Map<string, Glyph>();
  for (const [ch, def] of Object.entries(UP)) {
    const rows = def.split('|');
    const w = rows[0]?.length ?? 1;
    const g = blank(w);
    place(g, rows, 0, 2);
    m.set(ch, { w, rows: g });
  }
  for (const [ch, def] of Object.entries(LOW)) {
    const rows = def.split('|');
    const w = Math.max(...rows.map((r) => r.length));
    const g = blank(w);
    place(g, rows, 0, 2);
    m.set(ch, { w, rows: g });
  }
  m.set(' ', { w: 3, rows: blank(3) });
  for (const [ch, [base, acc]] of Object.entries(COMPOSED)) {
    const b = m.get(base);
    if (!b) continue;
    const rows = [...b.rows];
    const upper = base === base.toUpperCase();
    if (acc === 'cedilla') {
      place(rows, ['.#', '#.'], Math.max(0, Math.floor(b.w / 2) - 1), 9);
    } else {
      const a = ACCENTS[acc] as string[];
      const ax = Math.max(0, Math.floor((b.w - (a[0]?.length ?? 1)) / 2 + (acc === 'acute' ? 0.5 : 0)));
      if (base === 'i') {
        rows[2] = '.';
        rows[3] = '.';
        m.set(ch, { w: 2, rows: rows.map((r) => (r + '.').slice(0, 2)) });
        const g = m.get(ch) as Glyph;
        place(g.rows, a, 0, 2);
        continue;
      }
      place(rows, a, ax, upper ? 0 : 2);
    }
    m.set(ch, { w: b.w, rows });
  }
  cache = m;
  return m;
}

/** Largura de um texto em pixels (1px de espaçamento entre glifos). */
export function textWidth(s: string): number {
  const f = getFont();
  let w = 0;
  for (const ch of s) w += ((f.get(ch) ?? f.get('?'))?.w ?? 3) + 1;
  return Math.max(0, w - 1);
}
